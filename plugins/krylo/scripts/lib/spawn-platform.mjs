// Cross-platform child-process invocation helper.
//
// Found while building Cross-Harness (docs/adr/0030-cross-harness-advisory-workers.md):
// on Windows, `child_process.spawnSync('claude', [...], { shell: false })`
// fails outright with EINVAL, because `claude`/`codex` (like most npm-
// installed CLIs) resolve to a `.cmd` shim on Windows, and Node.js refuses
// to exec a `.cmd`/`.bat` file directly without a shell -- .cmd files are
// not real executables; only cmd.exe can interpret them. The naive fix,
// `shell: true`, is unsafe: Node's own runtime emits
// "DEP0190: Passing args to a child process with shell option true can
// lead to security vulnerabilities, as the arguments are not escaped, only
// concatenated" -- verified directly: an argv element containing `&&` was
// genuinely executed as a second shell command when `shell: true` was used.
//
// SUPERSEDED APPROACH, kept here as a documented record of why it does NOT
// work: an earlier version of this module wrapped every invocation as
// `cmd.exe /d /s /c <command> <args...>` with `shell: false`, reasoning
// that Windows' own CreateProcess argument-vector passing (not shell string
// concatenation) would keep every element inert. A fresh independent
// Security Reviewer found and reproduced a real, working bypass: an argv
// element containing an embedded double-quote character (e.g.
// `x" & echo pwned> PWNED.txt & rem "`) genuinely created a file on disk.
// Root cause: Node's CreateProcess-level argv quoting is correct for the
// FINAL target process's own C-runtime argv parsing, but cmd.exe (the
// process actually being launched by that call) RE-PARSES the resulting
// command line under its own, different grammar -- an embedded `"`
// prematurely closes cmd.exe's own quoted region, and everything after it
// is interpreted as literal cmd.exe syntax (`&`, `>`, etc.), regardless of
// how carefully Node quoted the argument for the eventual real target. The
// existing test suite's own metacharacter payloads (no embedded `"`)
// passed cleanly and gave false assurance; they never exercised this path.
//
// THE FIX: never invoke cmd.exe at all. `.cmd` shims generated by npm's
// own `cmd-shim` tool (used for essentially every globally-installed
// Windows npm CLI, confirmed directly for both `claude.cmd` and
// `codex.cmd` in this environment) are a thin, extremely stable, textually
// simple wrapper around a REAL target: either a native `.exe` directly, or
// `node.exe <script.js>`. resolveWindowsShimTarget() below extracts that
// real target and invokes IT directly with `shell: false` -- a real
// executable target has no reparsing step at all (Windows' CreateProcess
// argv passing is unconditionally safe for a non-shell target, the same
// guarantee every other `shell:false` spawn site in this codebase already
// relies on for a plain `.exe`). If a shim does not match the known,
// well-documented npm cmd-shim format, this FAILS CLOSED (returns null) --
// callers must treat that as capability-unavailable, never silently fall
// back to the disproven cmd.exe-wrapping approach.
//
// On POSIX platforms, this is a no-op: the command is invoked directly,
// shell:false, exactly as every other spawn site in this codebase already
// does (no shim/reparsing layer exists there to begin with).

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

/**
 * Kill an entire process tree rooted at pid. Necessary in addition to
 * spawnSync's own `timeout` option: on Windows, that option only signals
 * the DIRECT child. On POSIX, spawnSync's own timeout kill already reaches
 * the direct child; nothing further is needed there.
 */
export function killProcessTree(pid) {
  if (!Number.isInteger(pid) || pid <= 0) return;
  if (os.platform() !== 'win32') {
    // A fresh independent Security Reviewer found this branch previously
    // called `process.kill(-pid, 'SIGKILL')` despite this function's own
    // comment already stating POSIX needs nothing further -- the child is
    // never spawned with `detached: true`, so no process group with id
    // `pid` exists; the call would normally throw ESRCH and be silently
    // swallowed below, but after spawnSync's own timeout kill has already
    // reaped the child, the OS is free to recycle that PID to an unrelated
    // process before this runs, in which case SIGKILL could hit an
    // unrelated process group. Made a genuine no-op to match what the
    // comment already claimed.
    return;
  }
  try {
    spawnSync('taskkill', ['/pid', String(pid), '/t', '/f'], { shell: false, timeout: 5000, stdio: 'ignore' });
  } catch {
    // Best-effort: the process may have already exited on its own.
  }
}

/**
 * The literal set of directories `PATH` actually lists, resolved to
 * absolute, lowercase, trailing-separator-stripped form for exact
 * membership comparison. Reads whichever env key case-insensitively spells
 * "path" (Windows itself treats env var names case-insensitively, and this
 * process's own `process.env.PATH` is not guaranteed to be the exact key
 * name a differently-cased inherited environment used).
 *
 * A RELATIVE `PATH` entry (a bare `.`, a relative segment, or a driveless
 * Windows path like `C:` without a root) is dropped, never resolved: an
 * independent review found `path.resolve(entry)` on a relative entry
 * resolves it against THIS PROCESS'S OWN cwd -- during Cross-Harness worker
 * capability detection that cwd is the untrusted project root -- which
 * partially revived the exact cwd-shadow exploit this module's caller
 * (`resolveOnPath`) exists to close: a relative `.` entry plus a decoy
 * planted in that same cwd made the decoy pass this membership check even
 * though it is not a real PATH-installed target. A relative `PATH` entry is
 * already meaningless for locating a genuine system binary in any case.
 */
/**
 * Canonicalize a directory path for exact-membership comparison.
 * fs.realpathSync.native resolves symlinks/junctions AND, critically on
 * Windows, expands an 8.3 short-name form (e.g. `RUNNER~1`) to its real
 * long-name form -- confirmed via a real GitHub Actions Windows runner
 * failure: `where.exe` returned a candidate under a short-name path while
 * the PATH entry (from a freshly created temp directory) was in long-name
 * form, so the plain `path.resolve().toLowerCase()` comparison this
 * function used before never matched, and a genuine PATH-installed target
 * was wrongly reported as unavailable (a fail-CLOSED false negative, not a
 * security hole, but a real functional regression). Falls back to the
 * plain resolved form if realpath fails (e.g. the directory does not
 * exist) -- comparison then simply cannot match, which is the same safe
 * "unavailable" outcome as before this fix for a nonexistent directory.
 */
function canonicalDir(dirPath) {
  const resolved = path.resolve(dirPath).replace(/[\\/]+$/, '');
  try {
    return fs.realpathSync.native(resolved).toLowerCase();
  } catch {
    return resolved.toLowerCase();
  }
}

function pathDirectorySet() {
  const rawPathKey = Object.keys(process.env).find((k) => k.toLowerCase() === 'path');
  const rawPath = rawPathKey ? process.env[rawPathKey] : undefined;
  if (typeof rawPath !== 'string' || rawPath === '') return new Set();
  return new Set(
    rawPath
      .split(path.delimiter)
      .map((entry) => entry.trim())
      .filter(Boolean)
      .filter((entry) => path.isAbsolute(entry))
      .map((entry) => canonicalDir(entry)),
  );
}

/**
 * Resolve `command` to an absolute path via the OS's own PATH search
 * (`where` on Windows), preferring a `.cmd` result (PATHEXT's own default
 * preference order, and the shape resolveWindowsShimTarget() below knows
 * how to parse). Returns null if nothing is found.
 *
 * A fresh independent Security Reviewer found and reproduced, with a
 * working exploit, that Windows' `where.exe` searches the CURRENT
 * DIRECTORY before PATH -- confirmed directly: `where codex`, run from a
 * directory containing an attacker-planted `codex.cmd`, lists that file
 * FIRST, ahead of the real PATH-installed one. For a Cross-Harness worker
 * launch (docs/adr/0030-cross-harness-advisory-workers.md) or a
 * project-scoped hook launcher (docs/adr/0032-codex-project-scoped-hook-enforcement.md),
 * that cwd is the untrusted project root -- writable by the model through
 * KRYLO's own ordinary, risk-gate-permitted Write tool. An earlier version
 * of this fix pinned `where`'s own cwd to `os.tmpdir()`; a SECOND
 * independent Security Reviewer, re-checking that exact fix, reproduced
 * that this only RELOCATED the vulnerability rather than closing it: (a)
 * `os.tmpdir()`'s own root is itself an equally Write-reachable location
 * (confirmed: a decoy planted directly there is still picked first), and
 * (b) `os.tmpdir()` is computed from the `TEMP`/`TMP` environment
 * variables, so redirecting either back to the project root fully revives
 * the original exploit -- no KRYLO-named sentinel gates a bare `TEMP`/`TMP`
 * assignment. No cwd is trustworthy for this purpose, by construction: cwd
 * only ever describes where a process happens to be running, never what a
 * human actually approved as an executable location. The real fix does not
 * try to find a safe cwd at all -- it validates the RESULT: after `where`
 * returns its candidates, every one is checked against the literal
 * directories `PATH` itself lists (pathDirectorySet(), above), and only a
 * candidate whose own containing directory is an exact PATH member is ever
 * accepted. A decoy anywhere else -- cwd, tmpdir, or any other writable
 * location not itself listed in PATH -- is rejected outright, regardless
 * of where `where` was run from or what it returned first.
 */
function resolveOnPath(command) {
  if (path.isAbsolute(command) && fs.existsSync(command)) return command;
  try {
    const res = spawnSync('where', [command], { encoding: 'utf8', shell: false, timeout: 5000, cwd: os.tmpdir() });
    if (res.status !== 0 || typeof res.stdout !== 'string') return null;
    const allCandidates = res.stdout.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
    const pathDirs = pathDirectorySet();
    const candidates = allCandidates.filter((c) => pathDirs.has(canonicalDir(path.dirname(c))));
    if (candidates.length === 0) return null;
    const cmdCandidate = candidates.find((c) => c.toLowerCase().endsWith('.cmd'));
    const exeCandidate = candidates.find((c) => c.toLowerCase().endsWith('.exe'));
    return cmdCandidate || exeCandidate || candidates[0] || null;
  } catch {
    return null;
  }
}

// Matches npm cmd-shim's own generated line shape (verified directly
// against this environment's real claude.cmd/codex.cmd): one or two
// double-quoted absolute paths -- optionally with %dp0%/%_prog%-style
// batch variables already substituted by the caller below -- immediately
// followed by a bare `%*` token marking "forward all arguments here",
// nothing else on the line. Deliberately conservative: anything not
// matching this exact shape is treated as unrecognized (fail closed).
const SHIM_TARGET_LINE_RE = /^"([^"]+)"(?:\s+"([^"]+)")?\s+%\*\s*$/;

/**
 * Parse a `.cmd` shim's content for the real target it ultimately invokes.
 * Returns { command, prefixArgs } on a recognized match, or null.
 */
function parseShimContent(shimPath, content) {
  const shimDir = path.dirname(shimPath);
  // npm cmd-shim's own two batch-variable conventions, substituted the same
  // way `%~dp0`/the shim's own `SET _prog=...` logic would at runtime.
  const substituted = content
    .replace(/%~dp0%?/gi, `${shimDir}\\`)
    .replace(/%dp0%/gi, `${shimDir}\\`)
    .replace(/%_prog%/gi, fs.existsSync(path.join(shimDir, 'node.exe')) ? `${shimDir}\\node.exe` : 'node');

  const lines = substituted.split(/\r?\n/).map((l) => l.trim());
  for (let i = lines.length - 1; i >= 0; i -= 1) {
    const line = lines[i];
    if (line === '' || line.startsWith('@') || line.startsWith('::') || line.startsWith('REM ') || line.startsWith('SET ') || line.startsWith('IF ') || line.startsWith('GOTO') || line.startsWith(':') || line.toUpperCase().startsWith('CALL') || line.toUpperCase() === 'SETLOCAL' || line.toUpperCase() === 'ENDLOCAL' || line.toUpperCase().startsWith('EXIT')) {
      continue;
    }
    // The real invocation line may be preceded by control-flow junk on the
    // same line (codex.cmd's `endLocal & goto ... || title ... & "..."`) --
    // only the FINAL `"..." [%*|"..." %*]` suffix is what actually runs.
    const suffixMatch = /("[^"]+"(?:\s+"[^"]+")?\s+%\*)\s*$/.exec(line);
    const target = suffixMatch ? suffixMatch[1] : line;
    const match = SHIM_TARGET_LINE_RE.exec(target);
    if (match) {
      const [, first, second] = match;
      return second
        ? { command: first, prefixArgs: [second] }
        : { command: first, prefixArgs: [] };
    }
  }
  return null;
}

/**
 * Resolve a `.cmd` shim path to its real, directly-invokable target
 * ({ command, prefixArgs }), or null if it cannot be safely resolved.
 * Never throws.
 */
export function resolveWindowsShimTarget(shimPath) {
  try {
    if (!fs.existsSync(shimPath)) return null;
    const content = fs.readFileSync(shimPath, 'utf8');
    const resolved = parseShimContent(shimPath, content);
    if (!resolved) return null;
    // The shim's own fallback (npm's codex.cmd: "SET _prog=node" when no
    // colocated node.exe exists, relying on PATH) yields a bare command
    // name here, not an absolute path -- resolve IT via PATH search too,
    // rather than treating "not a literal existing file named './node'" as
    // a parse failure. Confirmed necessary against the real installed
    // codex.cmd in this environment, which does exactly this.
    const resolvedCommand = path.isAbsolute(resolved.command)
      ? (fs.existsSync(resolved.command) ? resolved.command : null)
      : resolveOnPath(resolved.command);
    if (!resolvedCommand) return null;
    return { command: resolvedCommand, prefixArgs: resolved.prefixArgs };
  } catch {
    return null;
  }
}

/**
 * Adjust a { command, args } pair for safe, shell:false spawning on the
 * current platform. Callers should always spawn with the RETURNED command
 * and args (never the originals directly) and always with shell:false.
 * Returns null on Windows when `command` cannot be safely resolved to a
 * real, directly-invokable target -- callers MUST treat that as
 * capability-unavailable (e.g. WORKER_UNAVAILABLE/SPAWN_FAILED), never
 * fall back to invoking cmd.exe directly.
 */
export function platformSpawnTarget(command, args) {
  if (os.platform() !== 'win32') {
    return { command, args };
  }
  const resolvedPath = resolveOnPath(command);
  if (!resolvedPath) return null;
  if (resolvedPath.toLowerCase().endsWith('.exe')) {
    // A real executable: shell:false is unconditionally safe, no reparsing
    // step exists for a direct CreateProcess target.
    return { command: resolvedPath, args };
  }
  if (resolvedPath.toLowerCase().endsWith('.cmd') || resolvedPath.toLowerCase().endsWith('.bat')) {
    const shimTarget = resolveWindowsShimTarget(resolvedPath);
    if (!shimTarget) return null;
    return { command: shimTarget.command, args: [...shimTarget.prefixArgs, ...args] };
  }
  return null;
}
